#! /usr/bin/env python3

"""
Compute-node half of the two-stage MaMiCo couette build.

Assumes build-couette-login.py has already populated build/LAMMPS (git clone)
and build/_deps/kokkos-src (FetchContent tarball). Prunes the build directory
down to those network-derived sources, then configures and builds entirely
offline: no git clone, no git pull, no FetchContent download.

Two things are deliberately NOT kept across the stages:
  * _deps/kokkos-build  - Kokkos is configured with Kokkos_ARCH_NATIVE ON, so
                          object code built on a login node may use the wrong
                          microarchitecture. Pass --keep-kokkos-build to reuse.
  * LAMMPS/build        - same argument, plus the USER-MAMICO headers are
                          recopied from the current MaMiCo tree on every run.
                          Pass --keep-lammps-build to reuse.

Anything in build/ that is neither a known CMake artefact nor a preserved
source is MOVED into build/_pruned_<timestamp>/ rather than deleted, so run
output (CSVs, log.lammps*, couette.xml, FoamSetup) survives a mistake.

An alternative to build-couette.py for clusters whose compute nodes have no
outbound network; build-couette.py itself is unchanged.
"""

import argparse
import getpass
import json
import os
import shlex
import shutil
import socket
import subprocess
import sys
import time
from pathlib import Path

MANIFEST_NAME = ".offline-prefetch.json"

# Regenerated by CMake on every configure, safe to remove outright.
CMAKE_ARTEFACTS = {
    "CMakeCache.txt",
    "CMakeFiles",
    "CTestTestfile.cmake",
    "Makefile",
    "cmake_install.cmake",
    "cmake_packages",
    "compile_commands.json",
    "couette",
    "generated",
    "install_manifest.txt",
    "libsimplemd.a",
}

# Network-derived, never removed by this script.
PRESERVED = {"LAMMPS", "_deps", "openfoam", MANIFEST_NAME}

MD_SOLVERS = dict(md="SIMPLE_MD", ls1="LS1_MARDYN", lammps="LAMMPS_MD")


class ChangeDir:
    def __init__(self, tmp_dir):
        self.tmp_dir = tmp_dir

    def __enter__(self):
        self.last_dir = os.getcwd()
        os.chdir(self.tmp_dir)

    def __exit__(self, exc_type, exc_value, traceback):
        os.chdir(self.last_dir)


def shell(cmd):
    print(f"{getpass.getuser()}@{socket.gethostname()}:{os.getcwd()}$ {cmd}", flush=True)
    return subprocess.call(["/bin/bash", "-c", "set -o pipefail; " + cmd + " 2>&1"])


def git_repo_root(start):
    start = Path(start)
    if not start.is_dir():
        start = start.parent
    if not start.is_dir():
        return None
    with ChangeDir(start):
        root = subprocess.getoutput("git rev-parse --show-toplevel")
    return None if root.startswith("fatal:") else Path(root)


def resolve_source(explicit):
    """-S > $MAMICO_DIR > repo holding this script > repo holding cwd."""
    candidates = [
        Path(explicit).resolve() if explicit else None,
        Path(os.environ["MAMICO_DIR"]).resolve() if os.environ.get("MAMICO_DIR") else None,
        git_repo_root(Path(__file__).resolve()),
        git_repo_root(Path.cwd()),
    ]
    for candidate in candidates:
        if candidate is None:
            continue
        if (candidate / "CMakeLists.txt").is_file() and (candidate / "coupling").is_dir():
            return candidate
    sys.exit(
        "Could not locate the MaMiCo source tree.\n"
        "Pass -S/--source <path-to-MaMiCo> or export MAMICO_DIR."
    )


def check_prerequisites(build_dir, md_solver):
    problems = []
    kokkos_src = build_dir / "_deps" / "kokkos-src"
    if not (kokkos_src / "CMakeLists.txt").is_file():
        problems.append(f"Kokkos source missing at {kokkos_src}")
    if md_solver == "lammps":
        lammps_dir = build_dir / "LAMMPS"
        if not (lammps_dir / "src" / "lammps.cpp").is_file():
            problems.append(f"LAMMPS source missing at {lammps_dir}")
        if not (lammps_dir / "lib" / "kokkos" / "CMakeLists.txt").is_file():
            problems.append("LAMMPS bundled lib/kokkos missing")
    if problems:
        print("::: Cannot build offline :::")
        for problem in problems:
            print(f"  - {problem}")
        print("\nRun build-couette-login.py on a login node first.")
        return False
    manifest_path = build_dir / MANIFEST_NAME
    if manifest_path.is_file():
        manifest = json.loads(manifest_path.read_text())
        print(f"::: Prefetch from {manifest.get('host')} at {manifest.get('created')}")
        print(f"::: LAMMPS commit {manifest.get('lammps_commit')}")
    else:
        print(f"::: No {MANIFEST_NAME}; assuming the sources present are the ones you want.")
    return True


def find_live_processes(build_dir):
    """Processes whose cwd or exe sits inside build_dir. Refuse to prune those."""
    live = []
    proc = Path("/proc")
    if not proc.is_dir():
        return live
    root = str(build_dir)
    for entry in proc.iterdir():
        if not entry.name.isdigit():
            continue
        for link in ("cwd", "exe"):
            try:
                target = os.readlink(entry / link)
            except OSError:
                continue
            if target == root or target.startswith(root + os.sep):
                try:
                    cmdline = (entry / "cmdline").read_bytes().replace(b"\0", b" ").decode().strip()
                except OSError:
                    cmdline = "?"
                live.append((entry.name, cmdline))
                break
    return live


def recently_touched(build_dir, idle_minutes):
    """Newest mtime among the top-level entries this script would disturb."""
    cutoff = time.time() - idle_minutes * 60
    newest = []
    for entry in build_dir.iterdir():
        if entry.name in PRESERVED:
            continue
        try:
            mtime = entry.stat().st_mtime
        except OSError:
            continue
        if mtime > cutoff:
            newest.append((entry.name, time.strftime("%H:%M:%S", time.localtime(mtime))))
    return newest


def prune(build_dir, keep_kokkos_build, keep_lammps_build, dry_run):
    stamp = time.strftime("%Y%m%dT%H%M%S")
    attic = build_dir / f"_pruned_{stamp}"
    to_delete = []
    to_move = []

    for entry in sorted(build_dir.iterdir()):
        if entry.name in PRESERVED or entry.name.startswith("_pruned_"):
            continue
        if entry.name in CMAKE_ARTEFACTS:
            to_delete.append(entry)
        else:
            to_move.append(entry)

    deps = build_dir / "_deps"
    if deps.is_dir():
        for entry in sorted(deps.iterdir()):
            # *-src and *-subbuild came off the network; *-build is object code.
            if entry.name.endswith("-build"):
                if entry.name == "kokkos-build" and keep_kokkos_build:
                    continue
                to_delete.append(entry)

    lammps_dir = build_dir / "LAMMPS"
    if lammps_dir.is_dir() and not keep_lammps_build:
        for name in ("build", "install"):
            if (lammps_dir / name).is_dir():
                to_delete.append(lammps_dir / name)

    print("\n::: Prune plan :::")
    for entry in to_delete:
        print(f"  delete  {entry.relative_to(build_dir)}")
    for entry in to_move:
        print(f"  move    {entry.relative_to(build_dir)}  ->  {attic.name}/")
    if not to_delete and not to_move:
        print("  (nothing to do)")
    print(f"  keep    {', '.join(sorted(PRESERVED))}")

    if dry_run:
        print("\n::: --dry-run, nothing changed :::")
        return False

    if to_move:
        attic.mkdir(exist_ok=True)
        for entry in to_move:
            shutil.move(str(entry), str(attic / entry.name))
    for entry in to_delete:
        shutil.rmtree(entry, ignore_errors=True) if entry.is_dir() else entry.unlink(missing_ok=True)
    return True


def inject_lammps_package(lammps_dir):
    """Add USER-MAMICO to LAMMPS' STANDARD_PACKAGES list, idempotently."""
    cmake_lists = lammps_dir / "cmake" / "CMakeLists.txt"
    lines = cmake_lists.read_text().splitlines(keepends=True)
    if any(line.strip() == "USER-MAMICO" for line in lines):
        return False
    for index, line in enumerate(lines):
        if line.strip() == "set(STANDARD_PACKAGES":
            lines.insert(index + 1, "USER-MAMICO" + os.linesep)
            cmake_lists.write_text("".join(lines))
            return False
    print("!!! Could not find 'set(STANDARD_PACKAGES' in LAMMPS cmake/CMakeLists.txt")
    return True


def stage_mamico_sources(source_dir, lammps_dir):
    """Refresh USER-MAMICO inside the LAMMPS tree from the current MaMiCo checkout."""
    target = lammps_dir / "src" / "USER-MAMICO"
    fix_dir = source_dir / "coupling" / "interface" / "impl" / "LAMMPS" / "USER-MAMICO"
    shutil.copytree(fix_dir, target, dirs_exist_ok=True)
    indexing = source_dir / "coupling" / "indexing"
    for name in ("IndexingService.cpp", "IndexingService.h", "Operations.h"):
        shutil.copy2(indexing / name, target)
    return inject_lammps_package(lammps_dir)


def build_lammps(source_dir, build_dir, with_mpi, jobs, cxx, cc):
    lammps_dir = build_dir / "LAMMPS"
    if (lammps_dir / "build" / "liblammps.so").is_file():
        print("::: Reusing existing LAMMPS build :::")
        return False
    print("::: Building LAMMPS offline :::")
    if stage_mamico_sources(source_dir, lammps_dir):
        return True
    lammps_build = lammps_dir / "build"
    lammps_install = lammps_dir / "install"
    lammps_build.mkdir(parents=True, exist_ok=True)
    lammps_install.mkdir(parents=True, exist_ok=True)
    args = [
        "-DPKG_KOKKOS=ON",
        "-DDOWNLOAD_KOKKOS=OFF",
        "-DEXTERNAL_KOKKOS=OFF",
        "-DPKG_USER-MAMICO=ON",
        "-DBUILD_SHARED_LIBS=ON",
        f"-DBUILD_MPI={'ON' if with_mpi else 'OFF'}",
        f"-DCMAKE_INSTALL_PREFIX={lammps_install}",
        f"-DCMAKE_CXX_FLAGS=-I {source_dir}",
    ]
    if cxx:
        args.append(f"-DCMAKE_CXX_COMPILER={cxx}")
    if cc:
        args.append(f"-DCMAKE_C_COMPILER={cc}")
    with ChangeDir(lammps_build):
        if shell(shlex.join(["cmake", *args, "../cmake/"])) != 0:
            return True
        if shell(shlex.join(["make", "-j", str(jobs)])) != 0:
            return True
        if shell("make install") != 0:
            return True
    return False


def open_foam_prefix(build_dir):
    """Prefer an OpenFOAM already in the environment (spack/module) over a local tree."""
    if os.environ.get("WM_PROJECT_DIR"):
        return None, os.environ["WM_PROJECT_DIR"]
    local = build_dir / "openfoam"
    if local.is_dir():
        for candidate in sorted(local.glob("OpenFOAM-v*")):
            bashrc = candidate / "etc" / "bashrc"
            if bashrc.is_file():
                return bashrc, str(candidate)
    return None, None


def build_mamico(source_dir, build_dir, args, foam_bashrc):
    kokkos_src = build_dir / "_deps" / "kokkos-src"
    cmake_args = [
        f"-DCMAKE_BUILD_TYPE={'DebugMD' if args.debug else 'DebugOptimized'}",
        f"-DKOKKOS_TARGET={args.kokkos_target}",
        f"-DBUILD_WITH_MPI={'ON' if args.with_mpi else 'OFF'}",
        f"-DBUILD_TESTING={'ON' if args.with_tests else 'OFF'}",
        f"-DMD_SIM={MD_SOLVERS[args.md_solver]}",
        f"-DBUILD_WITH_OPENFOAM={'ON' if args.with_foam else 'OFF'}",
        # Use the prefetched tarball in place; never contact the network.
        f"-DFETCHCONTENT_SOURCE_DIR_KOKKOS={kokkos_src}",
        "-DFETCHCONTENT_FULLY_DISCONNECTED=ON",
        "-DFETCHCONTENT_UPDATES_DISCONNECTED=ON",
    ]
    if args.no_disconnect:
        cmake_args = [a for a in cmake_args if "DISCONNECTED" not in a]
    if args.cxx:
        cmake_args.append(f"-DCMAKE_CXX_COMPILER={args.cxx}")
    if args.cc:
        cmake_args.append(f"-DCMAKE_C_COMPILER={args.cc}")
    if args.mpi_cxx:
        cmake_args.append(f"-DMPI_CXX_COMPILER={args.mpi_cxx}")
    if args.mpi_cc:
        cmake_args.append(f"-DMPI_C_COMPILER={args.mpi_cc}")

    if args.md_solver == "lammps":
        cmake_args.append("-DBUILD_WITH_LAMMPS=ON")
        cmake_args.append(f"-DLAMMPS_DIR={build_dir / 'LAMMPS'}")
    else:
        cmake_args.append("-DBUILD_WITH_LAMMPS=OFF")
    if args.md_solver == "ls1":
        cmake_args.append(f"-DLS1_SRC_DIR={source_dir / 'ls1'}")

    configure = shlex.join(["cmake", *cmake_args, str(source_dir)])
    make = shlex.join(["make", "-j", str(args.jobs), "couette"])
    if foam_bashrc is not None:
        configure = f"source {shlex.quote(str(foam_bashrc))}; {configure}"
        make = f"source {shlex.quote(str(foam_bashrc))}; {make}"

    couette_bin = build_dir / "couette"
    with ChangeDir(build_dir):
        if shell(configure) != 0:
            return None
        couette_bin.unlink(missing_ok=True)
        if shell(make) != 0:
            return None
    return couette_bin if couette_bin.is_file() else None


def resolve_mpi_defaults(args):
    """Fall back to the Intel MPI wrappers the loaded module points at."""
    root = os.environ.get("I_MPI_ROOT")
    if not root:
        return
    for attr, wrapper in (("mpi_cxx", "mpicxx"), ("mpi_cc", "mpicc")):
        if getattr(args, attr):
            continue
        candidate = Path(root) / "bin" / wrapper
        if candidate.is_file():
            setattr(args, attr, str(candidate))


def main():
    parser = argparse.ArgumentParser(
        description="Offline compute-node build of the MaMiCo couette example (stage 2 of 2)."
    )
    parser.add_argument("-S", "--source", help="MaMiCo source dir (default: $MAMICO_DIR or the enclosing git repo)")
    parser.add_argument("-s", "--md-solver", choices=MD_SOLVERS.keys(), required=True)
    parser.add_argument("-F", "--with-foam", action="store_true")
    parser.add_argument("-M", "--with-mpi", action="store_true")
    parser.add_argument("-T", "--with-tests", action="store_true")
    parser.add_argument("-d", "--debug", action="store_true")
    parser.add_argument("-j", "--jobs", default=8)
    parser.add_argument("-k", "--kokkos-target", default="OPENMP", choices=["CUDA", "OPENMP", "SERIAL"])
    parser.add_argument("--cxx", help="CMAKE_CXX_COMPILER")
    parser.add_argument("--cc", help="CMAKE_C_COMPILER")
    parser.add_argument("--mpi-cxx", help="MPI_CXX_COMPILER (default: $I_MPI_ROOT/bin/mpicxx)")
    parser.add_argument("--mpi-cc", help="MPI_C_COMPILER (default: $I_MPI_ROOT/bin/mpicc)")
    parser.add_argument("--keep-kokkos-build", action="store_true", help="Reuse _deps/kokkos-build instead of recompiling")
    parser.add_argument("--keep-lammps-build", action="store_true", help="Reuse LAMMPS/build instead of recompiling")
    parser.add_argument("--no-prune", action="store_true", help="Skip the prune step entirely")
    parser.add_argument("--no-disconnect", action="store_true", help="Do not force FetchContent offline mode")
    parser.add_argument("--dry-run", action="store_true", help="Show the prune plan and exit")
    parser.add_argument("--idle-minutes", type=int, default=10, help="Refuse to prune if build/ changed this recently")
    parser.add_argument("-y", "--yes", action="store_true", help="Do not ask before pruning")
    parser.add_argument("--force", action="store_true", help="Prune even if build/ looks busy")
    args = parser.parse_args()

    source_dir = resolve_source(args.source)
    build_dir = source_dir / "build"
    print(f"::: MaMiCo source : {source_dir}")
    print(f"::: Build dir     : {build_dir}")
    if not build_dir.is_dir():
        sys.exit(f"{build_dir} does not exist. Run build-couette-login.py first.")
    if not check_prerequisites(build_dir, args.md_solver):
        return 1

    if not args.no_prune:
        live = find_live_processes(build_dir)
        if live and not args.force:
            print("\n::: Refusing to prune: processes are using this build directory :::")
            for pid, cmdline in live:
                print(f"  pid {pid}: {cmdline[:100]}")
            print("\nUse a separate build directory, or --force if you are sure.")
            return 1
        busy = recently_touched(build_dir, args.idle_minutes)
        if busy and not args.force:
            print(f"\n::: Refusing to prune: entries changed in the last {args.idle_minutes} min :::")
            for name, when in busy:
                print(f"  {name} (modified {when})")
            print("\nA run may be in progress. Use --force, or raise --idle-minutes 0.")
            return 1
        if not args.dry_run and not args.yes and sys.stdin.isatty():
            prune(build_dir, args.keep_kokkos_build, args.keep_lammps_build, dry_run=True)
            if input("\nProceed? [y/N] ").strip().lower() not in ("y", "yes"):
                return 1
        if not prune(build_dir, args.keep_kokkos_build, args.keep_lammps_build, args.dry_run):
            return 0

    resolve_mpi_defaults(args)

    foam_bashrc = None
    if args.with_foam:
        foam_bashrc, foam_dir = open_foam_prefix(build_dir)
        if foam_dir is None:
            sys.exit(
                "BUILD_WITH_OPENFOAM needs OpenFOAM.\n"
                "Load it first (spack load openfoam / module load, or source its etc/bashrc),\n"
                "or run build-couette-login.py --download-foam on a login node."
            )
        origin = "environment" if foam_bashrc is None else f"local tree, sourcing {foam_bashrc}"
        print(f"::: OpenFOAM     : {foam_dir} ({origin})")

    started = time.time()
    if args.md_solver == "lammps":
        if build_lammps(source_dir, build_dir, args.with_mpi, args.jobs, args.cxx, args.cc):
            print("::: LAMMPS build failed :::")
            return 1

    couette_bin = build_mamico(source_dir, build_dir, args, foam_bashrc)
    elapsed = time.time() - started
    print(f"\n::: Completed in {elapsed / 60:.1f} min (successful: {couette_bin is not None}) :::")
    if couette_bin is None:
        return 1
    print(couette_bin)
    return 0


if __name__ == "__main__":
    sys.exit(main())
